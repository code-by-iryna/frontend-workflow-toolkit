#!/usr/bin/env python3
"""
Нагадування про skill `qa-agent` у момент приходу запиту.

Це UserPromptSubmit hook. Він читає текст запиту користувача і, якщо той
просить живу перевірку (тестування, пошук багів, "чи працює", "чи готово
до релізу"), підмішує в контекст нагадування застосувати skill `qa-agent`.

Навіщо це потрібно окремим hook'ом, якщо в самих skill'ах уже є текстові
правила: браузерні MCP-інструменти доступні напряму, тому виникає спокуса
"просто зайти й подивитись" замість того, щоб застосувати `qa-agent` — і
тоді втрачається весь його чек-лист (крос-браузерність, тач, edge cases,
негативні сценарії, збереження звіту). Текстове правило спрацьовує лише
якщо Claude узагалі відкриє потрібний skill; hook не залежить від цього.

На відміну від gate-git.py та gate-linear.py, цей hook НІЧОГО не блокує —
він лише додає контекст. Хибне спрацювання коштує один зайвий рядок
підказки, тому пороги свідомо не робились надто вузькими.
"""
import json
import re
import sys

# Патерни українською, російською та англійською — користувачка пише
# запити різними мовами, а skill-и написані українською.
TESTING_PATTERNS = [
    # пряме прохання протестувати
    r"протестуй|протестув|тестуван|тестув[аи]|тестиров|потестируй|потестить",
    r"\btest(ing|s)?\b|\bqa\b",
    # пошук багів
    r"\bбаг[иіов]?\b|\bбагів\b|\bbugs?\b|дефект|поламк|поломк",
    # перевірка працездатності
    r"чи (все|всі|воно|він|вона|це)?\s*прац[юєю]",
    r"работает ли|все ли работает|чи готово",
    r"не прац[юєю]|не работает|\bброкен\b|\bbroken\b",
    # готовність до релізу
    r"готов[оеый]{0,2}\s+(до|к)\s+реліз|готов[оеый]{0,2}\s+(до|к)\s+релиз",
    r"ready\s+for\s+release|ship\s+it",
    # перевірка в браузері
    r"в браузер|у браузер|in the browser",
    # мета-прохання задіяти всі скіли
    r"заді[йя]|задейств|усі потрібні скіли|все нужные скилы|all (the )?skills",
]

REMINDER = (
    "[hook: remind-qa-agent] Запит містить прохання про живу перевірку "
    "(тестування / пошук багів / чи працює). Застосуй skill `qa-agent` — "
    "саме skill, а не просто браузерні MCP-інструменти напряму: інакше "
    "втрачається його чек-лист (крос-браузерність Chromium/Gecko/WebKit, "
    "тач і мобільні в'юпорти, edge cases, негативні сценарії, UI-стани, "
    "мережеві контракти, збереження звіту у файл).\n"
    "Якщо запит поєднує аналіз коду і тестування — `qa-agent` застосовується "
    "РАЗОМ з `code-reviewer`, а не замість нього.\n"
    "Якщо браузер чи потрібний MCP недоступний — прямо скажи про це і познач "
    "живу перевірку як непроведену, не видавай статичний аналіз за тестування."
)


def main() -> None:
    try:
        payload = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        payload = {}

    prompt = str(payload.get("prompt", ""))

    for pattern in TESTING_PATTERNS:
        if re.search(pattern, prompt, re.IGNORECASE):
            print(
                json.dumps(
                    {
                        "hookSpecificOutput": {
                            "hookEventName": "UserPromptSubmit",
                            "additionalContext": REMINDER,
                        }
                    }
                )
            )
            return

    # Нічого не додаємо — запит не про живу перевірку.
    sys.exit(0)


if __name__ == "__main__":
    main()
